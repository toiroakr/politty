#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const coreDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const specDir = join(coreDir, "src/agent/spec");
// detect-agent's `exports` only exposes ".", so its files are read by path.
const upstreamDir = join(coreDir, "node_modules/detect-agent");

const { version } = JSON.parse(readFileSync(join(upstreamDir, "package.json"), "utf8"));
const agents = JSON.parse(readFileSync(join(upstreamDir, "agents.json"), "utf8"));

// The npm tarball does not ship testcases.json, so it comes from the git tag
// matching the installed package version.
const testcasesUrl = `https://raw.githubusercontent.com/vercel/detect-agent/v${version}/testcases.json`;
const response = await fetch(testcasesUrl);
if (!response.ok) {
  throw new Error(`Failed to fetch ${testcasesUrl}: ${response.status} ${response.statusText}`);
}
const testcases = await response.json();

const agentsPath = join(specDir, "agents.json");
const testcasesPath = join(specDir, "testcases.json");
const idsPath = join(coreDir, "src/agent/known-agent-ids.ts");

writeFileSync(agentsPath, `${JSON.stringify(agents, null, 2)}\n`);
writeFileSync(testcasesPath, `${JSON.stringify(testcases, null, 2)}\n`);
writeFileSync(
  idsPath,
  [
    `// Generated by scripts/sync-agent-spec.mjs from detect-agent@${version}. Do not edit.`,
    `export const KNOWN_AGENT_IDS = ${JSON.stringify(agents.agents.map((agent) => agent.name))} as const;`,
    "",
  ].join("\n"),
);

execFileSync("pnpm", ["exec", "oxfmt", agentsPath, testcasesPath, idsPath], {
  cwd: coreDir,
  stdio: "inherit",
});

console.log(`Synced detect-agent spec v${version}`);
